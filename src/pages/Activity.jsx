import { useEffect, useState } from "react";
import { api } from "../services/api";
import { Loading, ErrorState, Empty } from "../components/States";
const money = (n) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2,
  }).format(Number(n) || 0);
export default function Activity() {
  const [data, setData] = useState(null),
    [error, setError] = useState("");
  useEffect(() => {
    api("/dashboard/histories")
      .then(setData)
      .catch((e) => setError(e.message));
  }, []);
  if (error) return <ErrorState message={error} />;
  if (!data) return <Loading />;
  return (
    <>
      <div className="page-heading">
        <div>
          <span className="eyebrow">ACCOUNT LEDGER</span>
          <h1>Transaction activity</h1>
          <p>Review your recorded ROI and referral earnings.</p>
        </div>
      </div>
      <section className="panel table-panel">
        <div className="panel-heading">
          <div>
            <h3>ROI history</h3>
            <p>Daily returns by investment</p>
          </div>
        </div>
        <div className="table-scroll">
          <table>
            <thead>
              <tr>
                <th>Date</th>
                <th>Investment</th>
                <th>Status</th>
                <th className="align-right">Amount</th>
              </tr>
            </thead>
            <tbody>
              {data.roiHistory.length ? (
                data.roiHistory.map((x) => (
                  <tr key={x._id}>
                    <td>
                      {new Date(x.date).toLocaleDateString("en-IN", {
                        timeZone: "UTC",
                      })}
                    </td>
                    <td>{x.investment?.plan?.name || "Investment"}</td>
                    <td>
                      <span className="status-badge">{x.status}</span>
                    </td>
                    <td className="align-right amount-positive">
                      +{money(x.roiAmount.$numberDecimal)}
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan="4">
                    <Empty message="No ROI transactions yet." />
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </section>
      <section className="panel table-panel">
        <div className="panel-heading">
          <div>
            <h3>Referral income</h3>
            <p>Level-based income credited to your wallet</p>
          </div>
        </div>
        <div className="table-scroll">
          <table>
            <thead>
              <tr>
                <th>Date</th>
                <th>Generated by</th>
                <th>Level</th>
                <th>Status</th>
                <th className="align-right">Amount</th>
              </tr>
            </thead>
            <tbody>
              {data.levelIncomeHistory.length ? (
                data.levelIncomeHistory.map((x) => (
                  <tr key={x._id}>
                    <td>{new Date(x.date).toLocaleDateString("en-IN")}</td>
                    <td>{x.generatedBy?.fullName || "Network member"}</td>
                    <td>Level {x.level}</td>
                    <td>
                      <span className="status-badge">{x.status}</span>
                    </td>
                    <td className="align-right amount-positive">
                      +{money(x.incomeAmount.$numberDecimal)}
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan="5">
                    <Empty message="No referral income yet." />
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </section>
      <section className="panel table-panel">
        <div className="panel-heading">
          <div>
            <h3>Wallet ledger</h3>
            <p>Latest balance-affecting transactions</p>
          </div>
        </div>
        <div className="table-scroll">
          <table>
            <thead>
              <tr>
                <th>Date</th>
                <th>Type</th>
                <th>Description</th>
                <th className="align-right">Amount</th>
                <th className="align-right">Balance after</th>
              </tr>
            </thead>
            <tbody>
              {data.walletTransactions.length ? (
                data.walletTransactions.map((x) => (
                  <tr key={x._id}>
                    <td>{new Date(x.createdAt).toLocaleString("en-IN")}</td>
                    <td>{x.type}</td>
                    <td>{x.description}</td>
                    <td
                      className={`align-right ${Number(x.amount) >= 0 ? "amount-positive" : "amount-negative"}`}
                    >
                      {money(x.amount.$numberDecimal)}
                    </td>
                    <td className="align-right">{money(x.balanceAfter.$numberDecimal)}</td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan="5">
                    <Empty message="No wallet transactions yet." />
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </section>
    </>
  );
}
